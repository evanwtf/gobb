// Command zonetab writes internal/tz/zones.go from the zone.tab file of an IANA
// tz database release.
//
// Use the release whose version matches DATA in
// $(go env GOROOT)/lib/time/update.bash, because Go builds its own zone data from
// that release with PACKRATLIST=zone.tab. Every name in that file then loads
// with time.LoadLocation. From the repo root:
//
//	curl -fsSLO https://data.iana.org/time-zones/releases/tzdata2026c.tar.gz
//	tar xzf tzdata2026c.tar.gz zone.tab
//	go run ./scripts/zonetab -version 2026c zone.tab
//
// The command writes the file given by -out (default internal/tz/zones.go).
package main

import (
	"bufio"
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"os"
	"regexp"
	"slices"
	"strings"
)

var versionRE = regexp.MustCompile(`^[0-9]{4}[a-z]$`)

// zoneRE matches the name of a zone in zone.tab: Area/Location, with one more
// level at most.
var zoneRE = regexp.MustCompile(`^[A-Za-z]+(/[A-Za-z0-9_+-]+){1,2}$`)

// parse reads zone.tab and returns the sorted zone names. A line has five
// tab-separated columns (country codes, coordinates, zone, comments). The
// third is the zone. Lines that start with # are comments. A duplicate or a
// malformed name is an error.
func parse(r io.Reader) ([]string, error) {
	var names []string
	seen := map[string]bool{}
	sc := bufio.NewScanner(r)
	for n := 1; sc.Scan(); n++ {
		line := sc.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		cols := strings.Split(line, "\t")
		if len(cols) < 3 {
			return nil, fmt.Errorf("line %d: want at least 3 tab-separated columns, got %d", n, len(cols))
		}
		name := cols[2]
		switch {
		case !zoneRE.MatchString(name):
			return nil, fmt.Errorf("line %d: %q is not a zone name", n, name)
		case seen[name]:
			return nil, fmt.Errorf("line %d: %q appears twice", n, name)
		}
		seen[name] = true
		names = append(names, name)
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if len(names) == 0 {
		return nil, errors.New("no zone names found")
	}
	slices.Sort(names)
	return names, nil
}

// generate returns the source of zones.go for the zone names in r.
func generate(r io.Reader, version string) ([]byte, error) {
	if !versionRE.MatchString(version) {
		return nil, fmt.Errorf("version %q: want a tzdata version such as 2026c", version)
	}
	names, err := parse(r)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by scripts/zonetab from the zone.tab of tzdata %s; DO NOT EDIT.\n", version)
	fmt.Fprintf(&b, "//\n// To update it, take zone.tab from the IANA release whose version matches DATA in\n")
	fmt.Fprintf(&b, "// $(go env GOROOT)/lib/time/update.bash, then run from the repo root:\n//\n")
	fmt.Fprintf(&b, "//\tgo run ./scripts/zonetab -version %s zone.tab\n\n", version)
	fmt.Fprintf(&b, "package tz\n\n")
	fmt.Fprintf(&b, "// TZDataVersion is the IANA tz database release that Zones comes from.\n")
	fmt.Fprintf(&b, "const TZDataVersion = %q\n\n", version)
	fmt.Fprintf(&b, "// Zones lists every zone name of zone.tab, sorted.\nvar Zones = []string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	fmt.Fprintf(&b, "}\n")
	return format.Source(b.Bytes())
}

func main() {
	version := flag.String("version", "", "tzdata version of the zone.tab file, such as 2026c (required)")
	out := flag.String("out", "internal/tz/zones.go", "file to write")
	flag.Parse()
	if flag.NArg() != 1 || *version == "" {
		log.Fatal("usage: zonetab -version VERSION [-out FILE] zone.tab")
	}
	f, err := os.Open(flag.Arg(0))
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	src, err := generate(f, *version)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
